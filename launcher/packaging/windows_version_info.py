"""The Windows version resource of forza-launcher.exe (company, product, description, versions,
original file name), generated from forza_launcher/_version.py when PyInstaller builds the exe.

An executable with none of this, unsigned and packed by PyInstaller, is what Defender's machine
learning flags most often (#482, #354); with it, Explorer, Task Manager and antivirus reports
name the program and its version. forza-launcher.spec passes the text from `version_file_text`
to EXE(version=...). The Inno Setup script takes its numeric version from the command line:

    python launcher/packaging/windows_version_info.py 0.2.0      ->  0.2.0.0

This module imports nothing from PyInstaller, so the launcher tests run it anywhere.
"""
import re
import sys

# The same publisher as AppPublisher in installer.iss (launcher/test_windows_version_info.py checks it).
COMPANY = "Dyotson"
PRODUCT = "Forza Horizon 1: ReImagined"
DESCRIPTION = "Forza Horizon 1: ReImagined launcher"
INTERNAL_NAME = "forza-launcher"
ORIGINAL_FILENAME = "forza-launcher.exe"
COPYRIGHT = "Copyright (c) 2026 Dyotson and Forza Horizon 1: ReImagined contributors"

_LEADING_NUMBERS = re.compile(r"(\d+)(?:\.(\d+))?(?:\.(\d+))?(?:\.(\d+))?")


def numeric_version(version):
    """The four 16-bit numbers of a Windows file version from a launcher version.

    "0.2.0" -> (0, 2, 0, 0); "0.3.0-rc.1" -> (0, 3, 0, 0); the CI's development version
    "0.0.0-dev.abc1234" -> (0, 0, 0, 0). Only the leading dotted numbers count."""
    match = _LEADING_NUMBERS.match(str(version).strip().removeprefix("v"))
    if not match:
        raise ValueError(f"Not a version number: {version!r}")
    parts = tuple(int(part) for part in match.groups(default="0"))
    if max(parts) > 0xFFFF:
        raise ValueError(f"A Windows version number is at most 65535 per part: {version!r}")
    return parts


def dotted_version(version):
    """"0.2.0" -> "0.2.0.0": the four-part form Windows shows as the file version."""
    return ".".join(str(part) for part in numeric_version(version))


def version_file_text(version):
    """The text of a PyInstaller version file (the format of `pyi-grab_version`) for this launcher version."""
    numbers = numeric_version(version)
    strings = (
        ("CompanyName", COMPANY),
        ("FileDescription", DESCRIPTION),
        ("FileVersion", dotted_version(version)),
        ("InternalName", INTERNAL_NAME),
        ("LegalCopyright", COPYRIGHT),
        ("OriginalFilename", ORIGINAL_FILENAME),
        ("ProductName", PRODUCT),
        ("ProductVersion", str(version).strip().removeprefix("v")),
    )
    rows = ",\n          ".join(f"StringStruct({name!r}, {value!r})" for name, value in strings)
    return f"""# UTF-8
# Generated by launcher/packaging/windows_version_info.py; do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numbers!r},
    prodvers={numbers!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
          {rows}
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: windows_version_info.py <launcher version>")
    print(dotted_version(sys.argv[1]))

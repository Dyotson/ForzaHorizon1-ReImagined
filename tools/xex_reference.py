#!/usr/bin/env python3
"""Write launcher/forza_launcher/xex_reference.py: the fingerprints (SHA-1 prefixes of the loaded
image, section by section, in 64 KB pieces) of the executables the project is made for, which
the launcher compares a player's default.xex and facade DLLs with (forza_launcher/xexcheck.py).
Only hashes are written, never game bytes.

Usage: xex_reference.py GAME_DIR
  GAME_DIR  a folder with the supported (version 0.0.0.7) default.xex, XMediaFacade_default.xex
            and SpeechFacade_default.xex, e.g. extracted/game
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "launcher"))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from forza_launcher import xexcheck  # noqa: E402

MODULES = ("default.xex", "XMediaFacade_default.xex", "SpeechFacade_default.xex")


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    mods = {}
    for name in MODULES:
        raw = open(os.path.join(argv[1], name), "rb").read()
        fp = xexcheck.fingerprint(raw, name)
        if not fp["intact"]:
            raise SystemExit(f"{name}: the image does not match its own page digests")
        media, version, base, title, entry, _flags = xexcheck.header_info(raw)
        fp["header"] = [version, base, media]
        del fp["intact"]
        mods[name] = fp
    ident = hashlib.sha1(repr(mods).encode()).hexdigest()[:10]
    out = ['"""Generated by tools/xex_reference.py: fingerprints of the supported executables (version',
           '0.0.0.7): SHA-1 prefixes of 64 KB pieces of each section of the loaded image. Hashes only."""',
           f'REFERENCE_ID = "{ident}"', "", "MODULES = {"]
    for name, fp in mods.items():
        out.append(f'    "{name}": {{')
        out.append(f'        "header": ({fp["header"][0]}, {fp["header"][1]}, {fp["header"][2]:#010x}),   # version, base version, media id')
        out.append(f'        "image": {fp["image"]:#x},')
        out.append(f'        "entry": {fp["entry"]:#x},')
        out.append('        "sections": [')
        for sec_name, va, size, flags, hs in fp["sections"]:
            out.append(f'            [{sec_name!r}, {va:#x}, {size:#x}, {flags:#x}, [')
            for i in range(0, len(hs), 3):
                out.append("                " + " ".join(f'"{h}",' for h in hs[i:i + 3]))
            out.append("            ]],")
        out.append("        ],")
        out.append("    },")
    out.append("}")
    dest = os.path.join(ROOT, "launcher", "forza_launcher", "xex_reference.py")
    with open(dest, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {dest}: {sum(len(s[4]) for fp in mods.values() for s in fp['sections'])} hashes, id {ident}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
